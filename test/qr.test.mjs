// Both copies of the format information, as 15-bit numbers (bit 0 first, as placed).
function formatCopies({ size, modules }) {
  let first = 0;
  let second = 0;
  for (let i = 0; i < 15; i++) {
    if (modules[i < 6 ? i : i < 8 ? i + 1 : size - 15 + i][8]) first |= 1 << i;
    if (modules[8][i < 8 ? size - 1 - i : i === 8 ? 7 : 14 - i]) second |= 1 << i;
  }
  return [first, second];
}

test('qr: a short string is the exact symbol the reference draws, mask included', () => {
  const symbol = qrMatrix('MADRE');
  assert.equal(symbol.size, 21);
  assert.equal(symbol.modules.length, 21);
  assert.ok(symbol.modules.every((row) => row.length === 21 && row.every((on) => typeof on === 'boolean')));
  assert.deepEqual(rows(symbol), MADRE);
});

test('qr: pairing addresses of different lengths match the reference module for module', () => {
  for (const { text, ecc, version, rows: expected } of PAIRING) {
    const symbol = qrMatrix(text, { ecc });
    assert.equal(versionOf(symbol), version, text);
    assert.deepEqual(rows(symbol), expected, `${ecc} ${text}`);
  }
});

test('qr: the smallest version that fits, counted in UTF-8 bytes', () => {
  const at = (length, ecc, unit = 'a') => versionOf(qrMatrix(unit.repeat(length), { ecc }));
  // Byte capacity of versions 1, 9, 20 and 40 per level; 10 is where the count grows to 16 bits.
  for (const [ecc, v1, v9, v20, v40] of [['L', 17, 230, 858, 2953], ['M', 14, 180, 666, 2331], ['Q', 11, 130, 482, 1663], ['H', 7, 98, 382, 1273]]) {
    assert.equal(at(v1, ecc), 1, ecc);
    assert.equal(at(v1 + 1, ecc), 2, ecc);
    assert.equal(at(v9, ecc), 9, ecc);
    assert.equal(at(v9 + 1, ecc), 10, ecc);
    assert.equal(at(v20, ecc), 20, ecc);
    assert.equal(at(v20 + 1, ecc), 21, ecc);
    assert.equal(at(v40, ecc), 40, ecc);
    assert.throws(() => qrMatrix('a'.repeat(v40 + 1), { ecc }), /do not fit/);
  }
  assert.equal(at(7, 'M', 'ñ'), 1, 'fourteen bytes fit in version 1');
  assert.equal(at(8, 'M', 'ñ'), 2, 'sixteen do not');
  assert.equal(versionOf(qrMatrix('a'.repeat(14))), 1, 'M is the default level');
  assert.equal(versionOf(qrMatrix('a'.repeat(15))), 2, 'M is the default level');
  assert.throws(() => qrMatrix('a', { ecc: 'X' }), /unknown error correction level/);
});

test('qr: three finder patterns with light separators, and none in the fourth corner', () => {
  for (const text of ['MADRE', PAIRING[1].text, 'a'.repeat(400)]) {
    const { size, modules } = qrMatrix(text);
    const block = (top, left) => FINDER.map((_, r) => modules[top + r].slice(left, left + 7).map(Number).join(''));
    assert.deepEqual(block(0, 0), FINDER);
    assert.deepEqual(block(0, size - 7), FINDER);
    assert.deepEqual(block(size - 7, 0), FINDER);
    assert.notDeepEqual(block(size - 7, size - 7), FINDER);
    for (let i = 0; i < 8; i++) {
      for (const [r, c] of [[7, i], [i, 7], [7, size - 1 - i], [i, size - 8], [size - 8, i], [size - 1 - i, 7]]) {
        assert.equal(modules[r][c], false, `separator at ${r},${c}`);
      }
    }
  }
});

test('qr: timing patterns alternate between the finders, and the dark module is dark', () => {
  for (const ecc of ['L', 'M', 'Q', 'H']) {
    for (const text of ['MADRE', PAIRING[2].text, 'a'.repeat(700)]) {
      const { size, modules } = qrMatrix(text, { ecc });
      for (let i = 8; i < size - 8; i++) {
        assert.equal(modules[6][i], i % 2 === 0, `row 6, column ${i}`);
        assert.equal(modules[i][6], i % 2 === 0, `column 6, row ${i}`);
      }
      assert.equal(modules[size - 8][8], true);
    }
  }
});

test('qr: format information says the level twice, and version information the version twice', () => {
  for (const ecc of ['L', 'M', 'Q', 'H']) {
    for (const length of [5, 82, 300, 1200]) {
      const symbol = qrMatrix('a'.repeat(length), { ecc: ecc.toLowerCase() });
      const [first, second] = formatCopies(symbol);
      assert.equal(first, second, `${ecc} ${length}`);
      assert.equal((first ^ 0x5412) >> 13, LEVEL_BITS[ecc]);
      const version = versionOf(symbol);
      if (version < 7) continue;
      const { size, modules } = symbol;
      let above = 0;
      let left = 0;
      for (let i = 0; i < 18; i++) {
        if (modules[Math.floor(i / 3)][size - 11 + (i % 3)]) above |= 1 << i;
        if (modules[size - 11 + (i % 3)][Math.floor(i / 3)]) left |= 1 << i;
      }
      assert.equal(above, left);
      assert.equal(above >> 12, version);
    }
  }
});

test('qr: the SVG is one currentColor path the page sizes and paints, with an escaped label', () => {
  const svg = qrSvg('MADRE', { label: 'Pair "MADRE" <here> & now' });
  assert.match(svg, /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 25 25" role="img" aria-label="Pair &#34;MADRE&#34; &#60;here&#62; &#38; now"><path fill="currentColor" shape-rendering="crispEdges" d="[^"]+"\/><\/svg>$/);
  assert.ok(!/\s(width|height)=/.test(svg), 'a fixed size');
  assert.ok(!svg.includes('<rect'), 'a background');
  assert.equal(svg.match(/<path /g).length, 1);
  assert.match(qrSvg('MADRE'), /aria-label="QR"/);
  assert.match(qrSvg('MADRE', { margin: 0 }), /viewBox="0 0 21 21"/);
  assert.match(qrSvg('MADRE', { margin: 4 }), /viewBox="0 0 29 29"/);

  // The path redraws the matrix exactly, shifted by the quiet zone, one rectangle per run.
  const { size, modules } = qrMatrix('MADRE');
  const d = svg.match(/ d="([^"]+)"/)[1];
  const drawn = Array.from({ length: size }, () => Array(size).fill(false));
  let rects = 0;
  for (const [, x, y, width] of d.matchAll(/M(\d+) (\d+)h(\d+)v1h-\3z/g)) {
    rects++;
    for (let i = 0; i < Number(width); i++) drawn[Number(y) - 2][Number(x) - 2 + i] = true;
  }
  assert.equal(d.replace(/M(\d+) (\d+)h(\d+)v1h-\3z/g, ''), '');
  assert.deepEqual(drawn, modules);
  assert.equal(rects, MADRE.join('0').match(/1+/g).length, 'runs on a row were not merged');
});
